function multiQualityExperiment()

    % ============================================================
    % MULTI-QUALITY IMAGE COMPRESSION EXPERIMENT
    %
    % Compares Standard DCT and Adaptive DCT over multiple
    % quality levels.
    %
    % Quality Levels:
    % 20, 30, 40, 50, 60, 70, 80
    %
    % Metrics:
    % - Compressed File Size
    % - Compression Ratio
    % - Space Saving
    % - MSE
    % - PSNR
    % - Similarity
    % - Adaptive Block Distribution
    % ============================================================

    clc;
    close all;

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('       MULTI-QUALITY COMPRESSION EXPERIMENT\n');
    fprintf('============================================================\n');

    % ------------------------------------------------------------
    % PROJECT PATH
    % ------------------------------------------------------------

    projectRoot = fileparts(fileparts(mfilename('fullpath')));

    addpath(fullfile(projectRoot, 'src'));

    % ------------------------------------------------------------
    % ORIGINAL IMAGE
    % ------------------------------------------------------------

    originalPath = fullfile( ...
        projectRoot, ...
        'test_images', ...
        'peppers.png');

    if ~isfile(originalPath)
        error('Original image not found: %s', originalPath);
    end

    % ------------------------------------------------------------
    % RESULTS FOLDER
    % ------------------------------------------------------------

    resultsFolder = fullfile( ...
        projectRoot, ...
        'results', ...
        'multi_quality');

    if ~isfolder(resultsFolder)
        mkdir(resultsFolder);
    end

    % ------------------------------------------------------------
    % ORIGINAL FILE SIZE
    % ------------------------------------------------------------

    originalInfo = dir(originalPath);

    originalSizeKB = ...
        originalInfo.bytes / 1024;

    % ------------------------------------------------------------
    % QUALITY LEVELS
    % ------------------------------------------------------------

    qualityLevels = [20 30 40 50 60 70 80];

    numLevels = length(qualityLevels);

    % ------------------------------------------------------------
    % RESULT ARRAYS
    % ------------------------------------------------------------

    standardSize = zeros(numLevels,1);
    adaptiveSize = zeros(numLevels,1);

    standardRatio = zeros(numLevels,1);
    adaptiveRatio = zeros(numLevels,1);

    standardSaving = zeros(numLevels,1);
    adaptiveSaving = zeros(numLevels,1);

    standardMSE = zeros(numLevels,1);
    adaptiveMSE = zeros(numLevels,1);

    standardPSNR = zeros(numLevels,1);
    adaptivePSNR = zeros(numLevels,1);

    standardSimilarity = zeros(numLevels,1);
    adaptiveSimilarity = zeros(numLevels,1);

    adaptiveHighBlocks = zeros(numLevels,1);
    adaptiveMediumBlocks = zeros(numLevels,1);
    adaptiveLowBlocks = zeros(numLevels,1);

    % ============================================================
    % PROCESS EACH QUALITY LEVEL
    % ============================================================

    for index = 1:numLevels

        quality = qualityLevels(index);

        fprintf('\n');
        fprintf('------------------------------------------------------------\n');
        fprintf('Processing Quality Level: %d\n', quality);
        fprintf('------------------------------------------------------------\n');

        % ========================================================
        % STANDARD DCT
        % ========================================================

        fprintf('  Standard DCT compression... ');

        standardQualityFile = fullfile( ...
            resultsFolder, ...
            sprintf('standard_quality_%d.mat', quality));

        % Delete previous file if it exists
        if isfile(standardQualityFile)
            delete(standardQualityFile);
        end

        % Your actualCompression requires:
        % imagePath, quality, outputPath

        evalc( ...
            'actualCompression(originalPath, quality, standardQualityFile);');

        % Check file
        if ~isfile(standardQualityFile)
            error( ...
                'Standard compressed file was not created.');
        end

        fprintf('Done\n');

        % --------------------------------------------------------
        % STANDARD FILE SIZE
        % --------------------------------------------------------

        standardInfo = dir(standardQualityFile);

        standardSize(index) = ...
            standardInfo.bytes / 1024;

        % --------------------------------------------------------
        % STANDARD DECOMPRESSION
        % --------------------------------------------------------

        fprintf('  Standard DCT decompression... ');

        evalc( ...
            '[standardImage, standardMetrics] = decompressImage(standardQualityFile);');

        fprintf('Done\n');

        % --------------------------------------------------------
        % STANDARD METRICS
        % --------------------------------------------------------

        standardMSE(index) = ...
            standardMetrics.MSE;

        standardPSNR(index) = ...
            standardMetrics.PSNR;

        standardSimilarity(index) = ...
            standardMetrics.Similarity;

        standardRatio(index) = ...
            originalSizeKB / standardSize(index);

        standardSaving(index) = ...
            ((originalSizeKB - standardSize(index)) / ...
            originalSizeKB) * 100;

        % ========================================================
        % ADAPTIVE DCT
        % ========================================================

        fprintf('  Adaptive DCT compression... ');

        adaptiveQualityFile = fullfile( ...
            resultsFolder, ...
            sprintf('adaptive_quality_%d.mat', quality));

        % Delete previous file
        if isfile(adaptiveQualityFile)
            delete(adaptiveQualityFile);
        end

        % Your adaptive compressor also receives:
        % imagePath, quality, outputPath

        evalc( ...
            'actualAdaptiveCompression(originalPath, quality, adaptiveQualityFile);');

        % Check file
        if ~isfile(adaptiveQualityFile)
            error( ...
                'Adaptive compressed file was not created.');
        end

        fprintf('Done\n');

        % --------------------------------------------------------
        % ADAPTIVE FILE SIZE
        % --------------------------------------------------------

        adaptiveInfo = dir(adaptiveQualityFile);

        adaptiveSize(index) = ...
            adaptiveInfo.bytes / 1024;

        % --------------------------------------------------------
        % ADAPTIVE DECOMPRESSION
        % --------------------------------------------------------

        fprintf('  Adaptive DCT decompression... ');

        evalc( ...
            '[adaptiveImage, adaptiveMetrics] = decompressAdaptiveImage(adaptiveQualityFile);');

        fprintf('Done\n');

        % --------------------------------------------------------
        % ADAPTIVE METRICS
        % --------------------------------------------------------

        adaptiveMSE(index) = ...
            adaptiveMetrics.MSE;

        adaptivePSNR(index) = ...
            adaptiveMetrics.PSNR;

        adaptiveSimilarity(index) = ...
            adaptiveMetrics.Similarity;

        adaptiveRatio(index) = ...
            originalSizeKB / adaptiveSize(index);

        adaptiveSaving(index) = ...
            ((originalSizeKB - adaptiveSize(index)) / ...
            originalSizeKB) * 100;

        adaptiveHighBlocks(index) = ...
            adaptiveMetrics.HighDetailBlocks;

        adaptiveMediumBlocks(index) = ...
            adaptiveMetrics.MediumDetailBlocks;

        adaptiveLowBlocks(index) = ...
            adaptiveMetrics.LowDetailBlocks;

        % ========================================================
        % DISPLAY CURRENT RESULT
        % ========================================================

        fprintf('\n');

        fprintf( ...
            '  Standard DCT : %.2f KB | %.2f dB | %.2f:1\n', ...
            standardSize(index), ...
            standardPSNR(index), ...
            standardRatio(index));

        fprintf( ...
            '  Adaptive DCT : %.2f KB | %.2f dB | %.2f:1\n', ...
            adaptiveSize(index), ...
            adaptivePSNR(index), ...
            adaptiveRatio(index));

    end

    % ============================================================
    % CREATE RESULTS TABLE
    % ============================================================

    resultsTable = table( ...
        qualityLevels', ...
        standardSize, ...
        adaptiveSize, ...
        standardRatio, ...
        adaptiveRatio, ...
        standardSaving, ...
        adaptiveSaving, ...
        standardMSE, ...
        adaptiveMSE, ...
        standardPSNR, ...
        adaptivePSNR, ...
        standardSimilarity, ...
        adaptiveSimilarity, ...
        adaptiveHighBlocks, ...
        adaptiveMediumBlocks, ...
        adaptiveLowBlocks, ...
        'VariableNames', { ...
        'Quality', ...
        'StandardSizeKB', ...
        'AdaptiveSizeKB', ...
        'StandardCompressionRatio', ...
        'AdaptiveCompressionRatio', ...
        'StandardSpaceSaving', ...
        'AdaptiveSpaceSaving', ...
        'StandardMSE', ...
        'AdaptiveMSE', ...
        'StandardPSNR', ...
        'AdaptivePSNR', ...
        'StandardSimilarity', ...
        'AdaptiveSimilarity', ...
        'HighDetailBlocks', ...
        'MediumDetailBlocks', ...
        'LowDetailBlocks'});

    % ============================================================
    % DISPLAY FINAL TABLE
    % ============================================================

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('             MULTI-QUALITY RESULTS\n');
    fprintf('============================================================\n');

    disp(resultsTable);

    % ============================================================
    % SAVE MATLAB RESULTS
    % ============================================================

    save( ...
        fullfile( ...
        resultsFolder, ...
        'multiQualityResults.mat'), ...
        'resultsTable', ...
        'qualityLevels', ...
        'standardSize', ...
        'adaptiveSize', ...
        'standardRatio', ...
        'adaptiveRatio', ...
        'standardSaving', ...
        'adaptiveSaving', ...
        'standardMSE', ...
        'adaptiveMSE', ...
        'standardPSNR', ...
        'adaptivePSNR', ...
        'standardSimilarity', ...
        'adaptiveSimilarity', ...
        'adaptiveHighBlocks', ...
        'adaptiveMediumBlocks', ...
        'adaptiveLowBlocks');

    % ============================================================
    % SAVE CSV
    % ============================================================

    writetable( ...
        resultsTable, ...
        fullfile( ...
        resultsFolder, ...
        'multiQualityResults.csv'));

    % ============================================================
    % GRAPH 1 - QUALITY vs PSNR
    % ============================================================

    figure( ...
        'Name', ...
        'Quality vs PSNR', ...
        'NumberTitle', ...
        'off');

    plot( ...
        qualityLevels, ...
        standardPSNR, ...
        '-o', ...
        'LineWidth', ...
        2);

    hold on;

    plot( ...
        qualityLevels, ...
        adaptivePSNR, ...
        '-s', ...
        'LineWidth', ...
        2);

    hold off;

    title('Quality Level vs PSNR');

    xlabel('Quality Level');

    ylabel('PSNR (dB)');

    legend( ...
        'Standard DCT', ...
        'Adaptive DCT', ...
        'Location', ...
        'best');

    grid on;

    % ============================================================
    % GRAPH 2 - QUALITY vs FILE SIZE
    % ============================================================

    figure( ...
        'Name', ...
        'Quality vs File Size', ...
        'NumberTitle', ...
        'off');

    plot( ...
        qualityLevels, ...
        standardSize, ...
        '-o', ...
        'LineWidth', ...
        2);

    hold on;

    plot( ...
        qualityLevels, ...
        adaptiveSize, ...
        '-s', ...
        'LineWidth', ...
        2);

    hold off;

    title('Quality Level vs Compressed File Size');

    xlabel('Quality Level');

    ylabel('Compressed File Size (KB)');

    legend( ...
        'Standard DCT', ...
        'Adaptive DCT', ...
        'Location', ...
        'best');

    grid on;

    % ============================================================
    % GRAPH 3 - QUALITY vs COMPRESSION RATIO
    % ============================================================

    figure( ...
        'Name', ...
        'Quality vs Compression Ratio', ...
        'NumberTitle', ...
        'off');

    plot( ...
        qualityLevels, ...
        standardRatio, ...
        '-o', ...
        'LineWidth', ...
        2);

    hold on;

    plot( ...
        qualityLevels, ...
        adaptiveRatio, ...
        '-s', ...
        'LineWidth', ...
        2);

    hold off;

    title('Quality Level vs Compression Ratio');

    xlabel('Quality Level');

    ylabel('Compression Ratio');

    legend( ...
        'Standard DCT', ...
        'Adaptive DCT', ...
        'Location', ...
        'best');

    grid on;

    % ============================================================
    % GRAPH 4 - QUALITY vs SPACE SAVING
    % ============================================================

    figure( ...
        'Name', ...
        'Quality vs Space Saving', ...
        'NumberTitle', ...
        'off');

    plot( ...
        qualityLevels, ...
        standardSaving, ...
        '-o', ...
        'LineWidth', ...
        2);

    hold on;

    plot( ...
        qualityLevels, ...
        adaptiveSaving, ...
        '-s', ...
        'LineWidth', ...
        2);

    hold off;

    title('Quality Level vs Space Saving');

    xlabel('Quality Level');

    ylabel('Space Saving (%)');

    legend( ...
        'Standard DCT', ...
        'Adaptive DCT', ...
        'Location', ...
        'best');

    grid on;

    % ============================================================
    % GRAPH 5 - QUALITY vs MSE
    % ============================================================

    figure( ...
        'Name', ...
        'Quality vs MSE', ...
        'NumberTitle', ...
        'off');

    plot( ...
        qualityLevels, ...
        standardMSE, ...
        '-o', ...
        'LineWidth', ...
        2);

    hold on;

    plot( ...
        qualityLevels, ...
        adaptiveMSE, ...
        '-s', ...
        'LineWidth', ...
        2);

    hold off;

    title('Quality Level vs MSE');

    xlabel('Quality Level');

    ylabel('Mean Squared Error');

    legend( ...
        'Standard DCT', ...
        'Adaptive DCT', ...
        'Location', ...
        'best');

    grid on;

    % ============================================================
    % GRAPH 6 - ADAPTIVE BLOCK DISTRIBUTION
    % ============================================================

    figure( ...
        'Name', ...
        'Adaptive Block Distribution', ...
        'NumberTitle', ...
        'off');

    plot( ...
        qualityLevels, ...
        adaptiveHighBlocks, ...
        '-o', ...
        'LineWidth', ...
        2);

    hold on;

    plot( ...
        qualityLevels, ...
        adaptiveMediumBlocks, ...
        '-s', ...
        'LineWidth', ...
        2);

    plot( ...
        qualityLevels, ...
        adaptiveLowBlocks, ...
        '-^', ...
        'LineWidth', ...
        2);

    hold off;

    title('Adaptive Block Classification vs Quality');

    xlabel('Quality Level');

    ylabel('Number of Blocks');

    legend( ...
        'High Detail', ...
        'Medium Detail', ...
        'Low Detail', ...
        'Location', ...
        'best');

    grid on;

    % ============================================================
    % COMPLETION MESSAGE
    % ============================================================

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('       MULTI-QUALITY EXPERIMENT COMPLETED\n');
    fprintf('============================================================\n');

    fprintf('Original File Size : %.2f KB\n', ...
        originalSizeKB);

    fprintf('\n');

    fprintf('Results folder:\n');
    fprintf('%s\n', resultsFolder);

    fprintf('\n');

    fprintf('MATLAB results:\n');
    fprintf('%s\n', ...
        fullfile( ...
        resultsFolder, ...
        'multiQualityResults.mat'));

    fprintf('\n');

    fprintf('CSV results:\n');
    fprintf('%s\n', ...
        fullfile( ...
        resultsFolder, ...
        'multiQualityResults.csv'));

    fprintf('\n');

    fprintf('============================================================\n');

end